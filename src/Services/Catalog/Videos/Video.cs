using NpgsqlTypes;

namespace NewStore.Catalog.Videos;

public sealed class Video
{
    public const int TitleMaxLength = 120;

    public const int DescriptionMaxLength = 5000;

    /// <summary>The files every video that existed before drafts plays, and the seeded videos too (the migration writes the same strings).</summary>
    public const string SamplePlaylistPath = "hls/sample/master.m3u8";

    public const string SampleThumbnailPath = "hls/sample/thumbnail.jpg";

    public Guid Id { get; init; }

    public Guid ChannelId { get; init; }

    public required string Title { get; init; }

    public required string Description { get; init; }

    public int DurationSeconds { get; init; }

    public VideoStatus Status { get; init; }

    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>Null until Media publishes the video.</summary>
    public DateTimeOffset? PublishedAt { get; init; }

    /// <summary>Relative to <see cref="CatalogOptions.MediaBaseUrl"/>. Null for a draft.</summary>
    public string? PlaylistPath { get; init; }

    public string? ThumbnailPath { get; init; }

    /// <summary>Generated by PostgreSQL from <see cref="Title"/> and <see cref="Description"/>; never written by the app.</summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;
}
